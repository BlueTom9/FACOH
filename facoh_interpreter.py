class FACOHCallable:
    def __init__(
        self, name, filename, user_functions, objects, interpreter=None
    ):
        self.name = name
        self.filename = filename
        self.interpreter = interpreter
        self.user_functions = user_functions.copy()
        self.objects = objects.copy()

    def __call__(self, *args, **kwargs):
        interpreter = self.interpreter
        if interpreter is None:
            interpreter = Interpreter("", self.filename)
            interpreter.user_functions = self.user_functions
            interpreter.objects = self.objects
        return interpreter._invoke_user_function(
            self.name,
            list(args),
            kwargs
        )


