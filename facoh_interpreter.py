def _crypto_bytes(value):
    if isinstance(value, bytes):
        return value
    return str(value).encode("utf-8")


def _decode_encryption_key(key):
    if isinstance(key, bytes):
        raw_key = key
    else:
        try:
            raw_key = base64.urlsafe_b64decode(str(key).encode("ascii"))
        except (UnicodeEncodeError, binascii.Error, ValueError) as error:
            raise ValueError(
                "Key must be generated by generate_key or derive_key") from error
    if len(raw_key) not in (16, 24, 32):
        raise ValueError("AES-GCM keys must be 16, 24, or 32 bytes")
    return raw_key


def _encrypt_with_key(message, key, associated_data=None):
    raw_key = _decode_encryption_key(key)
    nonce = os.urandom(12)
    ciphertext = AESGCM(raw_key).encrypt(
        nonce,
        _crypto_bytes(message),
        None if associated_data is None else _crypto_bytes(associated_data)
    )
    return base64.urlsafe_b64encode(nonce + ciphertext).decode("ascii")


def _decrypt_with_key(token, key, associated_data=None):
    raw_key = _decode_encryption_key(key)
    try:
        encrypted = base64.b64decode(
            _crypto_bytes(token),
            altchars=b"-_",
            validate=True
        )
    except (binascii.Error, ValueError) as error:
        raise ValueError("Invalid encrypted token") from error
    if len(encrypted) < 28:
        raise ValueError("Encrypted token is too short")
    try:
        plaintext = AESGCM(raw_key).decrypt(
            encrypted[:12],
            encrypted[12:],
            None if associated_data is None
            else _crypto_bytes(associated_data)
        )
    except InvalidTag as error:
        raise ValueError(
            "Authentication failed: wrong key or modified token") from error
    try:
        return plaintext.decode("utf-8")
    except UnicodeDecodeError:
        return plaintext


def _generate_key():
    return base64.urlsafe_b64encode(os.urandom(32)).decode("ascii")


def _derive_key(password, salt=None, iterations=600000):
    if not isinstance(iterations, int) or not 100000 <= iterations <= 10000000:
        raise ValueError("iterations must be between 100000 and 10000000")
    if salt is None:
        raw_salt = os.urandom(16)
    elif isinstance(salt, bytes):
        raw_salt = salt
    else:
        try:
            raw_salt = base64.b64decode(
                _crypto_bytes(salt),
                altchars=b"-_",
                validate=True
            )
        except (binascii.Error, ValueError) as error:
            raise ValueError(
                "salt must be URL-safe base64 from derive_key") from error
    if len(raw_salt) < 16:
        raise ValueError("salt must be at least 16 bytes")
    derivation = PBKDF2HMAC(
        algorithm=hashes.SHA256(),
        length=32,
        salt=raw_salt,
        iterations=iterations
    )
    raw_key = derivation.derive(_crypto_bytes(password))
    return {
        "key": base64.urlsafe_b64encode(raw_key).decode("ascii"),
        "salt": base64.urlsafe_b64encode(raw_salt).decode("ascii"),
        "iterations": iterations
    }


class FACOHAESGCM:
    def __init__(self, key=None):
        self._key = _decode_encryption_key(
            key) if key is not None else os.urandom(32)

    def encrypt(self, message, associated_data=None):
        return _encrypt_with_key(message, self._key, associated_data)

    def decrypt(self, token, associated_data=None):
        return _decrypt_with_key(token, self._key, associated_data)

    def get_key(self):
        return base64.urlsafe_b64encode(self._key).decode("ascii")


class FACOHError(Exception):
    def __init__(self, message, line=None, column=None):
        super().__init__(message)
        self.message = message
        self.line = line
        self.column = column
        self.traceback = []

    def add_traceback(
        self, filename, function, line, column, source=None, length=1,
        depth=None
    ):
        self.traceback.append({
            "filename": filename,
            "function": function,
            "line": line,
            "column": column,
            "source": source,
            "length": length,
            "depth": depth
        })

    def format(self):
        result = "Traceback (most recent call last):\n"

        for frame in reversed(self.traceback):
            result += (
                f'  File "{frame["filename"]}", '
                f'line {frame["line"]}, '
                f'column {frame["column"]}, '
                f'in {frame["function"]}\n'
            )
            source = frame["source"]
            line = frame["line"]
            column = frame["column"]
            if source is not None and isinstance(line, int) and line > 0:
                source_lines = source.splitlines()
                if source.endswith(("\n", "\r")):
                    source_lines.append("")
                if line <= len(source_lines):
                    source_line = source_lines[line - 1]
                    column = column if isinstance(
                        column, int) and column > 0 else 1
                    caret_length = max(frame["length"], 1)
                    caret_length = min(
                        caret_length,
                        max(len(source_line) - column + 1, 1)
                    )
                    result += (
                        f'    {source_line}\n'
                        f'    {" " * (column - 1)}'
                        f'{"^" * caret_length}\n'
                    )

        result += f"\n{type(self).__name__}: {self.message}"

        return result


