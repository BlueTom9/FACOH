    def _bind_arguments(self, name, parameters, args, kwargs):
        if len(args) > len(parameters):
            raise FACOHValueError(
                f"Function '{name}' expected at most "
                f"{len(parameters)} argument(s), got {len(args)}"
            )

        bound_arguments = dict(zip(parameters, args))
        for parameter, argument in kwargs.items():
            if parameter not in parameters:
                raise FACOHValueError(
                    f"Function '{name}' got an unexpected "
                    f"keyword argument '{parameter}'"
                )
            if parameter in bound_arguments:
                raise FACOHValueError(
                    f"Function '{name}' got multiple values for "
                    f"argument '{parameter}'"
                )
            bound_arguments[parameter] = argument

        missing = [
            parameter
            for parameter in parameters
            if parameter not in bound_arguments
        ]
        if missing:
            raise FACOHValueError(
                f"Function '{name}' is missing required argument(s): "
                f"{', '.join(missing)}"
            )
        return bound_arguments

    def _invoke_user_function(self, name, args, kwargs):
        function = self.user_functions[name]
        return self._execute_function(
            name,
            function["parameters"],
            function["block"],
            args,
            kwargs
        )

    def _execute_function(
        self, name, parameters, block, args, kwargs, instance=None
    ):
        old_variables = self.variables
        bound_arguments = self._bind_arguments(
            name,
            parameters,
            args,
            kwargs
        )
        previous_parameters = {}
        if instance is None:
            self.variables = bound_arguments
        else:
            self.variables = instance["attributes"]
            previous_parameters = {
                parameter: (
                    parameter in self.variables,
                    self.variables.get(parameter)
                )
                for parameter in parameters
            }
            self.variables.update(bound_arguments)
        self.call_stack.append(name)
        try:
            self.execute(block)
        except ReturnSignal as signal:
            return signal.value
        finally:
            if instance is not None:
                for parameter, (existed, value) in previous_parameters.items():
                    if existed:
                        self.variables[parameter] = value
                    else:
                        self.variables.pop(parameter, None)
            self.call_stack.pop()
            self.variables = old_variables
        return None

    def run(self):
        self.tokens = self.lexer.lex()
        self.parser = Parser(self.tokens, "Interpreter", self.contents)
        self.parser_output = self.parser.parse_program()
        self.ast = self.parser_output[0]
        self.diagnostics = self.parser_output[1]
        for diagnostic in self.diagnostics:
            if diagnostic.type == "IndentationError":
                error = FACOHIndentationError(diagnostic.message)
            else:
                error = FACOHSyntaxError(diagnostic.message)
            error.add_traceback(
                self.filename,
                "<module>",
                diagnostic.line,
                diagnostic.column,
                self.contents,
                diagnostic.length
            )
            print(error.format())
            return
        try:
            self.execute(self.ast)
        except FACOHError as error:
            print(error.format())

    def _evaluate_fstring_expression(self, expression):
        lexer = Lexer(expression, "Interpreter")
        tokens, diagnostics = lexer.lex()
        parser = Parser((tokens, diagnostics), "Interpreter", expression)
        parsed_expression = parser.parse_expression()
        if parser.diagnostics or parser.peek()[0] != "EOF":
            raise FACOHValueError(
                f"Invalid expression in formatted string: {expression}"
            )
        return self.evaluate(parsed_expression)

    def _format_string(self, template):
        formatter = string.Formatter()
        result = []
        try:
            for literal, field_name, format_spec, conversion in (
                formatter.parse(template)
            ):
                result.append(literal)
                if field_name is None:
                    continue
                value = self._evaluate_fstring_expression(field_name)
                if conversion == "s":
                    value = str(value)
                elif conversion == "r":
                    value = repr(value)
                elif conversion == "a":
                    value = ascii(value)
                elif conversion is not None:
                    raise FACOHValueError(
                        f"Unsupported formatted string conversion "
                        f"'!{conversion}'"
                    )
                if format_spec:
                    format_spec = self._format_string(format_spec)
                result.append(format(value, format_spec))
        except FACOHError:
            raise
        except (ValueError, TypeError, KeyError, IndexError) as error:
            raise FACOHValueError(
                f"Invalid formatted string: {error}"
            ) from error
        return "".join(result)

    def evaluate(self, node):
        if node["type"] == "literal":
            if node["value"][0] in ["'", '"']:
                return ast.literal_eval(node["value"])
            elif node["value"] == "true":
                return True
            elif node["value"] == "false":
                return False
            elif "." in node["value"]:
                return float(node["value"])
            else:
                return int(node["value"])

        elif node["type"] == "fstring":
            return self._format_string(ast.literal_eval(node["value"][1:]))

        elif node["type"] == "Variable":
            var = node["name"]
            if var in self.variables:
                return self.variables[var]
            elif var in self.user_functions:
                return FACOHCallable(
                    var,
                    self.filename,
                    self.user_functions,
                    self.objects,
                    self
                )
            elif var in self.global_variables:
                return self.global_variables[var]
            else:
                raise FACOHNonExistantError(
                    f"Variable '{var}' does not exist"
                )
        elif node["type"] == "Call":
            args = node["arguments"]
            name = node["name"]
            evaluated_args = [
                self.evaluate(arg)
                for arg in args
            ]
            evaluated_kwargs = {
                parameter: self.evaluate(value)
                for parameter, value in node.get(
                    "keyword_arguments",
                    {}
                ).items()
            }
            if name in self.functions:
                function = self.functions[name]
                if name == "create_window":
                    evaluated_kwargs.setdefault(
                        "resource_directory",
                        os.path.dirname(os.path.abspath(self.filename))
                        if self.filename != "<module>"
                        else os.getcwd()
                    )
                try:
                    return function(*evaluated_args, **evaluated_kwargs)

                except ValueError:
                    raise FACOHValueError(
                        f"Invalid value passed to '{name}'"
                    )

                except TypeError:
                    raise FACOHTypeError(
                        f"Invalid arguments passed to '{name}'"
                    )

                except FileNotFoundError:
                    raise FACOHFileNotFoundError(
                        "File not found"
                    )

            if name in self.user_functions:
                return self._invoke_user_function(
                    name,
                    evaluated_args,
                    evaluated_kwargs
                )

            if name in self.extension_objects:
                try:
                    if name == "UI":
                        evaluated_kwargs.setdefault(
                            "resource_directory",
                            os.path.dirname(os.path.abspath(self.filename))
                            if self.filename != "<module>"
                            else os.getcwd()
                        )
                    return self.extension_objects[name](
                        *evaluated_args,
                        **evaluated_kwargs
                    )
                except ValueError:
                    raise FACOHValueError(
                        f"Invalid value passed to '{name}'"
                    )
                except TypeError:
                    raise FACOHTypeError(
                        f"Invalid arguments passed to '{name}'"
                    )

            if name in self.objects:
                if name in self.error_classes:
                    if len(evaluated_args) > 1:
                        raise FACOHValueError(
                            f"'{name}' expected 0 or 1 argument(s), "
                            f"got {len(evaluated_args)}"
                        )
                    message = (
                        str(evaluated_args[0])
                        if evaluated_args
                        else ""
                    )
                    return {
                        "object": name,
                        "attributes": {
                            "message": message
                        }
                    }
                instance = {
                    "object": name,
                    "attributes": {}
                }
                old_variables = self.variables
                try:
                    self.variables = instance["attributes"]
                    for object_definition in reversed(
                        self._object_lineage(name)
                    ):
                        self.execute(object_definition["initialization"])
                finally:
                    self.variables = old_variables
                return instance

            if name in self.variables:
                function = self.variables[name]
                if callable(function):
                    try:
                        return function(
                            *evaluated_args,
                            **evaluated_kwargs
                        )
                    except ValueError:
                        raise FACOHValueError(
                            f"Invalid value passed to '{name}'"
                        )
                    except TypeError:
                        raise FACOHTypeError(
                            f"Invalid arguments passed to '{name}'"
                        )

        elif node["type"] == "BinaryOperation":
            left = self.evaluate(node["left"])
            operator = node["operator"]
            right = self.evaluate(node["right"])

            try:
                if operator == "+":
                    return left + right
                elif operator == "-":
                    return left - right
                elif operator == "*":
                    return left * right
                elif operator == "/":
                    return left / right
                elif operator == "%":
                    return left % right
                elif operator == "**":
                    return left ** right
                elif operator == "=":
                    return left == right
                elif operator == "<":
                    return left < right
                elif operator == ">":
                    return left > right
                elif operator == "!=":
                    return left != right
                elif operator == "also":
                    return left and right
                elif operator == "or":
                    return left or right
                elif operator == "in":
                    return left in right
                elif operator == "!in":
                    return not left in right
                elif operator == "is":
                    return left is right
                elif operator == "!is":
                    return not left is right
            except ZeroDivisionError:
                raise FACOHZeroDivisionError(
                    "Cannot divide by zero"
                )
            except TypeError:
                raise FACOHTypeError(
                    "Invalid operation between types"
                )

        elif node["type"] == "UnaryOperation":
            operand = self.evaluate(node["operand"])
            operator = node["operator"]
            try:
                if operator == "-":
                    return -operand
                elif operator == "!":
                    return not operand
            except TypeError:
                raise FACOHTypeError(
                    "Invalid unary operation"
                )
        elif node["type"] == "MethodCall":
            obj = self.evaluate(node["object"])
            method_name = node["method"]
            evaluated_args = [
                self.evaluate(argument)
                for argument in node["arguments"]
            ]
            evaluated_kwargs = {
                parameter: self.evaluate(value)
                for parameter, value in node.get(
                    "keyword_arguments",
                    {}
                ).items()
            }
            if isinstance(obj, str):
                object_type = "String"
            elif isinstance(obj, list):
                object_type = "List"
            elif isinstance(obj, dict) and "object" not in obj:
                object_type = "Dictionary"
            else:
                object_type = None

            if object_type in self.builtin_objects:
                methods = self.builtin_objects[object_type]["methods"]

                if method_name not in methods:
                    raise FACOHNonExistantError(
                        f"Method '{method_name}' does not exist"
                    )
                try:
                    return methods[method_name](
                        obj,
                        *evaluated_args,
                        **evaluated_kwargs
                    )
                except IndexError:
                    raise FACOHIndexError("Index is out of range")
                except ValueError:
                    raise FACOHValueError(
                        f"Invalid value passed to '{method_name}'"
                    )
                except TypeError:
                    raise FACOHTypeError(
                        f"Invalid arguments passed to '{method_name}'"
                    )
            if isinstance(obj, dict) and "object" in obj:
                object_name = obj["object"]
                method = None
                for object_definition in self._object_lineage(object_name):
                    for current_method in object_definition["methods"]:
                        if current_method["name"] == method_name:
                            method = current_method
                            break
                    if method is not None:
                        break
                if method is None:
                    raise FACOHNonExistantError(
                        f"Method '{method_name}' does not exist"
                    )
                return self._execute_function(
                    method_name,
                    method["parameters"],
                    method["block"],
                    evaluated_args,
                    evaluated_kwargs,
                    obj
                )

            method = None
            try:
                method = getattr(obj, method_name)
            except AttributeError:
                pass

            if method is None:
                for map_name in ("FUNCTIONS", "OBJECTS"):
                    if hasattr(obj, map_name):
                        mapping = getattr(obj, map_name)
                        if isinstance(mapping, Mapping) and method_name in mapping:
                            method = mapping[method_name]
                            break

            if method is None:
                raise FACOHNonExistantError(
                    f"Method '{method_name}' does not exist"
                )

            if not callable(method):
                raise FACOHTypeError(
                    f"Attribute '{method_name}' is not callable"
                )
            try:
                return method(*evaluated_args, **evaluated_kwargs)
            except ValueError:
                raise FACOHValueError(
                    f"Invalid value passed to '{method_name}'"
                )
            except TypeError:
                raise FACOHTypeError(
                    f"Invalid arguments passed to '{method_name}'"
                )

        elif node["type"] == "Attribute":
            obj = self.evaluate(node["object"])
            attribute = node["attribute"]
            if isinstance(obj, dict) and "object" in obj:
                if attribute not in obj["attributes"]:
                    raise FACOHNonExistantError(
                        f"Attribute '{attribute}' does not exist"
                    )
                return obj["attributes"][attribute]
            try:
                return getattr(obj, attribute)
            except AttributeError:
                for map_name in ("FUNCTIONS", "OBJECTS"):
                    if hasattr(obj, map_name):
                        mapping = getattr(obj, map_name)
                        if isinstance(mapping, Mapping) and attribute in mapping:
                            return mapping[attribute]
                raise FACOHNonExistantError(
                    f"Attribute '{attribute}' does not exist"
                )

        elif node["type"] == "List":
            elements = node["elements"]
            evaluated_list = []
            for element in elements:
                evaluated_list.append(self.evaluate(element))
            return evaluated_list

        elif node["type"] == "Dictionary":
            contents = node["contents"]
            evaluated_dic = {}
            for key, value in contents.items():
                key = key[1:-1]
                evaluated_dic[key] = self.evaluate(value)
            return evaluated_dic

        elif node["type"] == "Index":
            indexed_object = self.evaluate({
                "type": "Variable",
                "name": node["object"]
            })
            index = self.evaluate(node["index"])
            try:
                return indexed_object[index]

            except IndexError:
                raise FACOHIndexError(
                    "Index is out of range"
                )
            except KeyError:
                raise FACOHKeyError(
                    f"Key '{index}' does not exist"
                )

            except TypeError:
                raise FACOHTypeError(
                    "Invalid index type"
                )

        elif node["type"] == "Slice":
            indexed_object = self.evaluate({
                "type": "Variable",
                "name": node["object"]
            })
            start = self.evaluate(node["start"])
            end = self.evaluate(node["end"])

            try:
                return indexed_object[start:end]

            except TypeError:
                raise FACOHTypeError(
                    "Invalid slice"
                )

    def execute(self, nodes):
        for node in nodes:
            line = node.get("line", 0)
            column = node.get("column", 0)
            try:
                if node["type"] == "Assignment":
                    value = self.evaluate(node["value"])
                    self.variables[node["name"]] = value

                elif node["type"] == "AttributeAssignment":
                    value = self.evaluate(node["value"])
                    obj = self.evaluate(node["object"])
                    if isinstance(obj, dict) and "object" in obj:
                        obj["attributes"][node["attribute"]] = value
                    else:
                        try:
                            setattr(obj, node["attribute"], value)
                        except AttributeError:
                            raise FACOHNonExistantError(
                                f"Attribute '{node['attribute']}' "
                                "cannot be assigned"
                            )

                elif node["type"] == "Obj":
                    name = node["name"]
                    self.objects[name] = {
                        "parent": node["parent"],
                        "initialization": node["initialization"],
                        "methods": node["methods"]
                    }

                elif node["type"] == "Call" or node["type"] == "MethodCall":
                    self.evaluate(node)

                elif node["type"] == "If":
                    condition = self.evaluate(node["condition"])
                    if condition:
                        self.execute(node["block"])
                    else:
                        if node["else_block"]:
                            self.execute(node["else_block"])

                elif node["type"] == "While":
                    block = node["block"]
                    condition = node["condition"]
                    break_appeared = False
                    try:
                        while self.evaluate(condition):
                            self.execute(block)
                    except BreakSignal:
                        break_appeared = True
                    if not break_appeared and node.get("else_block"):
                        self.execute(node["else_block"])

                elif node["type"] == "For":
                    break_appeared = False
                    iterable = self.evaluate(node["iterable"])
                    block = node["block"]
                    try:
                        for value in iterable:
                            self.variables[node["variable"]] = value
                            self.execute(block)
                    except BreakSignal:
                        break_appeared = True
                    if not break_appeared and node["else_block"]:
                        self.execute(node["else_block"])

                elif node["type"] == "break":
                    raise BreakSignal()

                elif node["type"] == "pass":
                    pass

                elif node["type"] == "Function":
                    name = node["name"]
                    parameters = node["parameters"]
                    block = node["block"]
                    self.user_functions[name] = {
                        "parameters": parameters,
                        "block": block
                    }

                elif node["type"] == "return":
                    value = self.evaluate(node["value"])
                    raise ReturnSignal(value)

                elif node["type"] == "throw":
                    value = self.evaluate(node["value"])
                    if isinstance(value, FACOHError):
                        raise value
                    if isinstance(value, dict) and "object" in value:
                        object_name = value["object"]
                        if object_name in self.error_classes:
                            message = value["attributes"].get("message", "")
                            error_class = self.error_classes[object_name]
                            raise error_class(message)
                    raise FACOHError(str(value))

                elif node["type"] == "try":
                    try:
                        self.execute(node["block"])
                    except Exception as error:
                        handled = False
                        for caught in node["caughts"].values():
                            if caught["type"] in self.error_classes and isinstance(error, self.error_classes[caught["type"]]):
                                if caught["var"] is not None:
                                    self.variables[caught["var"]] = error
                                self.execute(caught["block"])
                                handled = True
                                break
                        if not handled:
                            raise
                    else:
                        if node["else_block"]:
                            self.execute(node["else_block"])
                    finally:
                        if node["finally_block"]:
                            self.execute(node["finally_block"])

                elif node["type"] == "fileoc":
                    try:
                        expression = self.evaluate(node["expression"])
                        var = node["var"]
                        block = node["block"]
                        value = expression.__enter__()

                    except FileNotFoundError:
                        raise FACOHFileNotFoundError(
                            "File not found"
                        )

                    if var:
                        self.variables[var] = value
                    try:
                        self.execute(block)
                    except BaseException as error:
                        if not expression.__exit__(
                            type(error),
                            error,
                            error.__traceback__
                        ):
                            raise
                    else:
                        expression.__exit__(
                            None,
                            None,
                            None
                        )

                elif node["type"] == "use":
                    name = node["name"]
                    from_name = node["from"]
                    var_name = node["var"]
                    if from_name is None and name in self.builtin_modules:
                        self.variables[var_name or name] = (
                            self.builtin_modules[name]
                        )

                    elif from_name is None and name in self.builtin_extensions:
                        path = self.builtin_extensions[name]
                        if not os.path.isabs(path):
                            path = os.path.join(
                                os.path.dirname(os.path.abspath(__file__)),
                                path
                            )
                        extension = self.extension_cache.get(path)
                        if extension is None:
                            spec = importlib.util.spec_from_file_location(
                                f"facoh_extension_{name}", path)
                            extension = importlib.util.module_from_spec(spec)
                            spec.loader.exec_module(extension)
                            self._register_extension(extension, name)
                            self.extension_cache[path] = extension
                        self.variables[var_name or name] = extension

                    else:
                        file_name = from_name if from_name is not None else name
                        self._load_fch_objects(
                            file_name,
                            name if from_name is not None else None,
                            self.filename
                        )
                        if (
                            from_name is not None
                            and var_name is not None
                            and name in self.objects
                        ):
                            self.objects[var_name] = self.objects[name]

                elif node["type"] == "delete":
                    var = node["target"]["name"]
                    if var not in self.variables:
                        raise FACOHNonExistantError(
                            f"Variable '{var}' does not exist"
                        )
                    del self.variables[var]

            except FACOHError as error:
                depth = len(self.call_stack)
                if not error.traceback or error.traceback[-1]["depth"] != depth:
                    error.add_traceback(
                        self.filename,
                        self.call_stack[-1] if self.call_stack else "<module>",
                        line,
                        column,
                        self.contents,
                        depth=depth
                    )
                raise