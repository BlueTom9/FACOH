    def _object_lineage(self, object_name):
        lineage = []
        visited = set()

        while object_name is not None:
            if object_name in visited:
                raise FACOHValueError(
                    f"Circular object inheritance involving '{object_name}'"
                )
            visited.add(object_name)

            object_definition = self.objects.get(object_name)
            if object_definition is None:
                raise FACOHNonExistantError(
                    f"Parent object '{object_name}' does not exist"
                )

            lineage.append(object_definition)
            object_name = object_definition["parent"]

        return lineage

    def _register_extension(self, extension, extension_name):
        exported_functions = getattr(extension, "FUNCTIONS", {})
        exported_objects = getattr(extension, "OBJECTS", {})
        if not isinstance(exported_functions, Mapping):
            raise FACOHValueError(
                f"Extension '{extension_name}' FUNCTIONS must be a mapping"
            )
        if not isinstance(exported_objects, Mapping):
            raise FACOHValueError(
                f"Extension '{extension_name}' OBJECTS must be a mapping"
            )

        functions = {}
        objects = {}
        for export_name, function in exported_functions.items():
            if not isinstance(export_name, str) or not callable(function):
                raise FACOHValueError(
                    f"Extension '{extension_name}' has an invalid function export"
                )
            if (
                export_name in self.functions
                or export_name in self.user_functions
                or export_name in self.objects
                or export_name in self.extension_objects
            ):
                raise FACOHValueError(
                    f"Extension function '{export_name}' conflicts with an existing name"
                )
            functions[export_name] = function

        for export_name, object_type in exported_objects.items():
            if not isinstance(export_name, str) or not callable(object_type):
                raise FACOHValueError(
                    f"Extension '{extension_name}' has an invalid object export"
                )
            if (
                export_name in self.functions
                or export_name in self.user_functions
                or export_name in self.objects
                or export_name in self.extension_objects
                or export_name in functions
            ):
                raise FACOHValueError(
                    f"Extension object '{export_name}' conflicts with an existing name"
                )
            objects[export_name] = object_type

        self.functions.update(functions)
        self.extension_objects.update(objects)

    def _resolve_fch_path(self, file_name, importer_filename):
        if importer_filename == "<module>":
            base_directory = os.getcwd()
        else:
            base_directory = os.path.dirname(importer_filename)
        path = os.path.abspath(os.path.join(base_directory, file_name))

        if os.path.splitext(path)[1] == ".py":
            raise FACOHValueError(
                "Python files can only be imported as built-in extensions"
            )
        if not os.path.exists(path):
            if os.path.exists(path + ".fch"):
                path += ".fch"
            else:
                raise FACOHFileNotFoundError(
                    f"File '{file_name}' does not exist"
                )
        if os.path.splitext(path)[1] != ".fch":
            raise FACOHValueError(
                f"Unsupported file type '{os.path.splitext(path)[1]}'"
            )

        return path

    def _load_fch_objects(self, file_name, requested_name, importer_filename):
        path = self._resolve_fch_path(file_name, importer_filename)
        if path in self.loading_modules:
            raise FACOHValueError(
                f"Circular FACOH module import involving '{file_name}'"
            )

        if path not in self.module_cache:
            with open(path, "r") as file:
                contents = file.read()
            lexer = Lexer(contents, "Interpreter")
            tokens = lexer.lex()
            parser = Parser(tokens, "Interpreter", contents)
            ast, diagnostics = parser.parse_program()
            if diagnostics:
                diagnostic = diagnostics[0]
                if diagnostic.type == "IndentationError":
                    raise FACOHIndentationError(diagnostic.message)
                raise FACOHSyntaxError(diagnostic.message)
            self.module_cache[path] = ast

        ast = self.module_cache[path]
        self.loading_modules.add(path)
        try:
            for imported_node in ast:
                if imported_node["type"] != "use":
                    continue
                imported_name = imported_node["name"]
                imported_from = imported_node["from"]
                if (
                    imported_from is None
                    and (
                        imported_name in self.builtin_extensions
                        or imported_name in self.builtin_modules
                    )
                ):
                    continue
                self._load_fch_objects(
                    imported_from if imported_from is not None else imported_name,
                    imported_name if imported_from is not None else None,
                    path
                )
        finally:
            self.loading_modules.remove(path)

        definitions = {
            node["name"]: node
            for node in ast
            if node["type"] == "Obj"
        }
        if requested_name is None:
            names_to_register = [
                node["name"]
                for node in ast
                if node["type"] == "Obj"
            ]
        else:
            if requested_name not in definitions:
                raise FACOHNonExistantError(
                    f"Object '{requested_name}' does not exist in "
                    f"'{file_name}'"
                )

            names_to_register = []
            included_names = set()

            def include_object(name):
                if name in included_names:
                    return
                included_names.add(name)
                definition = definitions[name]
                parent = definition["parent"]
                if parent in definitions:
                    include_object(parent)
                names_to_register.append(name)

            include_object(requested_name)

        for name in names_to_register:
            definition = definitions[name]
            self.objects[name] = {
                "parent": definition["parent"],
                "initialization": definition["initialization"],
                "methods": definition["methods"]
            }

